package de.swiesend.secretservice.functional.interfaces;

import de.swiesend.secretservice.functional.SearchMode;
import java.util.List;
import java.util.Map;
import java.util.Optional;
import java.util.function.Function;

public interface CollectionInterface extends AutoCloseable {

    /**
     * Clear the collection password.
     *
     * @return true, if password could be cleared else false.
     */
    boolean clear();

    /**
     * Create an item in the collection.
     *
     * @param label  The label is a description. It is not a unique identifier.
     * @param secret The secret to be stored. One can encrypt the secret in beforehand,
     *               to avoid unwanted access from malicious applications.
     * @return item path, which is a unique reference generated by the provider
     */
    Optional<String> createItem(String label, CharSequence secret);

    /**
     * Create an item in the collection.
     *
     * @param label      The label is a description. It is not a unique identifier.
     * @param secret     The secret to be stored. One can encrypt the secret in beforehand,
     *                   to avoid unwanted access from malicious applications.
     * @param attributes Attributes are provided as a mapping of custom keys and values.
     *                   Applications often identify their secrets using the key `application`
     *                   and their application name as value and providing a unique identifier
     *                   for a specific secret in order to find it by its attributes instead
     *                   of the generated item path.
     *                   <p>
     *                   e.g.:
     *                   <code>
     *                   {
     *                   "application": "APPLICATION_NAME",
     *                   "uuid": "f773dd93-4869-4897-be9d-c53f5b43f904"
     *                   }
     *                   </code>
     * @return item path, which is a unique reference generated by the provider
     */
    Optional<String> createItem(String label, CharSequence secret, Map<String, String> attributes);

    /**
     * Delete this collection, unless it is a default collection; see {@link #isDefault()}.
     *
     * @return whether the collection was deleted
     */
    boolean delete();

    /**
     * Whether this is a default collection, which {@link #delete()} does not delete: the one the
     * provider's {@code default} alias points to, or gnome-keyring's login or session collection.
     */
    boolean isDefault();

    boolean deleteItem(String objectPath);

    boolean deleteItems(List<String> objectPaths);

    Optional<Map<String, String>> getAttributes(String objectPath);

    Optional<List<String>> getItems(Map<String, String> attributes);

    /**
     * Search all items using substring matching against the given mode.
     *
     * @param query case-insensitive substring to search for; empty string returns all items
     * @param mode  which field to match against
     * @return unmodifiable list of matching D-Bus object paths (never null)
     */
    List<String> search(String query, SearchMode mode);

    /**
     * Search all items using fuzzy (Levenshtein) matching against the given mode.
     * Falls back to substring matching when {@code maxDistance} is 0.
     *
     * @param query       case-insensitive query string
     * @param mode        which field to match against
     * @param maxDistance maximum edit distance to consider a match
     * @return unmodifiable list of matching D-Bus object paths (never null)
     */
    List<String> search(String query, SearchMode mode, int maxDistance);

    Optional<String> getItemLabel(String objectPath);

    boolean setItemLabel(String objectPath, String label);

    boolean setLabel(String label);

    Optional<String> getLabel();

    Optional<String> getId();

    /**
     * Retrieve a decrypted secret by its object path.
     *
     * <p><b>Security note:</b> The caller is responsible for clearing the returned {@code char[]}
     * after use (e.g., {@code Arrays.fill(chars, '\0')}) to prevent sensitive material from
     * lingering in heap memory. Prefer {@link #withSecret(String, Function)} which handles
     * cleanup automatically.</p>
     *
     * @param objectPath the D-Bus object path of the item
     * @return the decrypted secret as a char array, or empty if the item does not exist or is locked
     */
    Optional<char[]> getSecret(String objectPath);

    /**
     * Access a decrypted secret within a callback, guaranteeing the secret bytes are cleared
     * from memory after the callback returns (or throws).
     *
     * <p>This is the recommended way to access secrets. The library decrypts the secret,
     * passes the {@code char[]} to the callback, and zeroes the array in a {@code finally}
     * block -- the caller never needs to manage cleanup.</p>
     *
     * <p>Example usage:</p>
     * <pre>{@code
     * Optional<Boolean> authenticated = collection.withSecret(itemPath, secret -> {
     *     return checkPassword(secret);
     * });
     * }</pre>
     *
     * @param objectPath the D-Bus object path of the item
     * @param callback   a function that receives the decrypted secret and returns a non-null result.
     *                   If the callback returns {@code null}, the result is indistinguishable from
     *                   a missing secret (both yield {@code Optional.empty()}). Callbacks that need
     *                   to express "no value" should return a wrapper type (e.g., {@code Optional<T>})
     *                   or a sentinel value instead of {@code null}.
     * @param <R>        the return type of the callback
     * @return the callback's result wrapped in Optional, or empty if the secret could not be
     *         retrieved <b>or</b> the callback returned {@code null}
     */
    <R> Optional<R> withSecret(String objectPath, Function<char[], R> callback);

    /**
     * Retrieve all decrypted secrets in this collection.
     *
     * <p><b>Security note:</b> The caller is responsible for clearing each returned {@code char[]}
     * after use (e.g., {@code Arrays.fill(chars, '\0')}) to prevent sensitive material from
     * lingering in heap memory. Prefer {@link #withSecrets(Function)} which handles
     * cleanup automatically. Requires user permission to unlock the collection.</p>
     *
     * @return a map of item object paths to their decrypted secrets, or empty if unavailable
     */
    Optional<Map<String, char[]>> getSecrets();

    /**
     * Access all decrypted secrets within a callback, guaranteeing all secret bytes are cleared
     * from memory after the callback returns (or throws).
     *
     * <p>This is the recommended way to access multiple secrets. The library decrypts all
     * secrets, passes the map to the callback, and zeroes every {@code char[]} value in
     * a {@code finally} block. Requires user permission to unlock the collection.</p>
     *
     * <p>Example usage:</p>
     * <pre>{@code
     * Optional<List<String>> labels = collection.withSecrets(secrets -> {
     *     return secrets.entrySet().stream()
     *         .filter(e -> Arrays.equals(e.getValue(), "target".toCharArray()))
     *         .map(Map.Entry::getKey)
     *         .toList();
     * });
     * }</pre>
     *
     * @param callback a function that receives the map of object paths to decrypted secrets
     *                 and returns a non-null result. If the callback returns {@code null}, the
     *                 result is indistinguishable from a retrieval failure (both yield
     *                 {@code Optional.empty()}).
     * @param <R>      the return type of the callback
     * @return the callback's result wrapped in Optional, or empty if secrets could not be
     *         retrieved <b>or</b> the callback returned {@code null}
     */
    <R> Optional<R> withSecrets(Function<Map<String, char[]>, R> callback);

    boolean isLocked();

    /**
     * Locks the collection. A provider that locks only through a prompt, as KeePassXC does, has
     * that prompt carried out; after {@link #disablePrompt()} it is dismissed instead, and the
     * collection stays unlocked.
     *
     * @return whether the collection is locked afterwards
     */
    boolean lock();

    /**
     * Makes the user confirm access, against CVE-2018-19358. {@link #getSecrets()} and
     * {@link #withSecrets(Function)} require it; {@link #deleteItem(String)} and
     * {@link #deleteItems(List)} ask for it first. Reading a single secret does not.
     *
     * <p>Where the provider locks without a prompt, as gnome-keyring does, the collection is
     * locked and then unlocked through the provider's dialog, once per collection object. A
     * provider that locks only through a prompt, as KeePassXC does, confirms access to its secrets
     * itself, and the collection is used as it is.</p>
     *
     * @return whether the collection is unlocked afterwards
     */
    boolean unlockWithUserPermission();

    /**
     * Update an item's label, secret and attributes. A part that is {@code null} stays as it is.
     *
     * <p>A locked item is unlocked first, as {@link #getSecret(String)} unlocks it, which can show
     * the provider's dialog. An item that stays locked is not changed at all.</p>
     *
     * @param objectPath the item's object path
     * @param label      the new label, or {@code null}
     * @param password   the new secret, or {@code null}; an empty one is refused, as by
     *                   {@link #createItem(String, CharSequence, Map)}
     * @param attributes the attributes that replace the item's, or {@code null}
     * @return whether every part that was given has been changed; {@code false} for an item that
     *         stayed locked
     */
    boolean updateItem(String objectPath, String label, CharSequence password, Map<String, String> attributes);

    boolean lockItem(String objectPath);

    boolean unlockItem(String objectPath);

    boolean disablePrompt();

    boolean enablePrompt();

    /**
     * Detects the currently active Secret Service provider and returns its display name.
     *
     * @return display name such as {@code "KeePassXC"}, {@code "gnome-keyring"},
     *         {@code "unknown"}, or {@code "N/A"}
     * @see de.swiesend.secretservice.ProviderDetector#detect(org.freedesktop.dbus.connections.impl.DBusConnection)
     */
    String getProvider();

    /**
     * Detects the currently active Secret Service provider as a typed enum constant.
     *
     * @return the detected {@link de.swiesend.secretservice.ProviderDetector.Provider}
     */
    de.swiesend.secretservice.ProviderDetector.Provider detectProvider();

}
